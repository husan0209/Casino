/**
 * Лицевой счёт демо-сессии (заказано как `balance_demo` у донора).
 *
 * Демо играет ненастоящими фишками, но правила у него те же, что у кассы:
 * ставка списывается в момент броска, и нельзя ставить то, чего на счёту уже
 * нет. Если остаток не хранить, а каждый бросок пересчитывать от стартового
 * кредита, счёт не растёт от выигрышей и уходит в минус при ставке больше
 * старта — ровно то, что игрок читает как «можно играть на минус».
 */
export const DEMO_BALANCE_STORE = Symbol('DEMO_BALANCE_STORE')

export interface DemoSettlement {
  /** false — на момент списания ставки остатка не хватило; счёт не изменён. */
  accepted: boolean
  /** Остаток после шага (при отказе — тот, что был). */
  balance: string
}

export interface IDemoBalanceStore {
  /**
   * Один атомарный шаг: списать ставку и начислить выигрыш. Атомарность здесь
   * не косметика: между бросками игрок переставляет выигрыш ещё упавшего шара,
   * и без проверки «списали ≤ остатка» в один момент два броска тратят одни и
   * те же фишки дважды.
   */
  settle(args: {
    sessionToken: string
    startCredit: string
    bet: string
    win: string
  }): Promise<DemoSettlement>

  /**
   * Текущий остаток — для экранов состояния (`/session`, `/state`), которые
   * показывают баланс до первого броска. Без этого перезагрузка игры рисовала
   * бы стартовые 1000 поверх уже наигранного остатка.
   */
  peek(sessionToken: string, startCredit: string): Promise<string>
}
