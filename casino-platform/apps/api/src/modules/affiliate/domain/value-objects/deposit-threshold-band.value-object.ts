/**
 * Правило F4 (ТЗ ч.8 §13.2): депозит ровно на порог допуска.
 *
 * Классический признак «минималки»: перекупщик заводит трафик на минимально
 * возможный депозит, потому что меньше от порога уже не взять. Отличить такое
 * от честного первого платежа по одному факту нельзя, поэтому правило
 * НЕ блокирует: атрибуция квалифицируется и приносит комиссию, а строка уходит
 * к администратору с причиной `near_threshold_deposit` (колонка `reject_reason`
 * у квалифицированной записи — это флаг на разбор, не отказ).
 *
 * Граница симметричная, как сформулировано в ТЗ («в пределах 1% от порога»),
 * хотя снизу она почти никогда не срабатывает: депозит меньше порога не
 * квалифицируется вовсе.
 *
 * Порог 0 («без порога», дефолт настройки) отключает правило: сравнивать с
 * нулём бессмысленно, а 1% от нуля — тоже ноль, и любая сумма попадала бы
 * в «предел» только при точном совпадении с нулём.
 */
import { Decimal } from 'decimal.js'

/** Коридор вокруг порога, в котором депозит считается «впритык». */
export const NEAR_THRESHOLD_RATIO = new Decimal('0.01')

/**
 * `amountRub` — RUB-эквивалент одного завершённого пополнения (`amount_rub`
 * из `payment_requests`), `minDepositRub` — порог допуска той же программы.
 */
export function isNearThresholdDeposit(amountRub: string, minDepositRub: string): boolean {
  const threshold = new Decimal(minDepositRub)
  if (!threshold.gt(0)) {
    return false
  }
  const band = threshold.times(NEAR_THRESHOLD_RATIO)
  return new Decimal(amountRub).minus(threshold).abs().lte(band)
}
