/**
 * Правовые документы, акцепт которых журналируется (GAP-71, Terms §4 и §23).
 *
 * Это строковый union, а не TS-enum: значения совпадают с enum `LegalDocumentType`
 * в Prisma-схеме, и строковый union присваивается сгенерированному типу клиента
 * без кастов. TS-enum пришлось бы кастовать в каждом месте записи.
 */
export type LegalDocumentType = 'terms' | 'privacy' | 'cookies' | 'responsible_gaming'

/**
 * Единый источник версий публичных правовых документов.
 *
 * Константа в shared-пакете, а не в apps/web, потому что сервер не может
 * журналировать версию, которую «прислал клиент»: акцепт доказателен только
 * тогда, когда записанная версия сверена с тем, что сервер сам считает
 * действующим (Terms §4, §23). Поэтому web рендерит номер из этого реестра, а
 * API принимает от клиента только тот номер, который совпадает с реестром.
 *
 * Версия меняется вместе с текстом в apps/web/src/content/legal/*; история
 * версий не переиспользуется — одна версия = один зафиксированный текст.
 */
export const LEGAL_DOCUMENT_VERSIONS: Readonly<Record<LegalDocumentType, string>> = {
  // 1.2 (2026-10-07): верификация нужна для вывода сверх порога мелких выплат,
  // а не для любого вывода; пополнение явно без верхней суммы. Копия 1.1
  // осталась в архиве — то, что игрок принял под 1.1, не переписывается.
  terms: '1.2',
  privacy: '1.0',
  cookies: '1.0',
  responsible_gaming: '1.0',
}

/**
 * Документы, на которые игрок даёт согласие отметкой при регистрации. Это ровно
 * то, что стоит в чекбоксе («Мне 18+ лет. Я принимаю условия использования и
 * политику конфиденциальности»): cookie-политика и политика ответственной игры
 * отдельным согласием не закрываются, поэтому в журнал не пишутся.
 */
export const CONSENTED_ON_REGISTRATION: readonly LegalDocumentType[] = ['terms', 'privacy']
