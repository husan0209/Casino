-- Экономика Plinko перед запуском на реальные деньги.
--
-- 1) Возврат на деньги 99 → 97: 1 % маржи не покрывает стоимость вывода, а 97 %
--    — уровень агрегаторов. Демо остаётся щедрым (120 %): оно не выплачивает
--    денег и работает на конверсию.
-- 2) Валютная сетка — только RUB и USDT_TRC20. Лимиты ставки в карточке
--    (min_bet = 1, max_bet = 10000) заданы в рублях; для BTC-кошелька «min_bet = 1»
--    означало бы ставку в один биткоин, поэтому крипто-кошельки на Plinko не
--    пускаем, пока не сделаем пересчёт лимита из RUB-эквивалента по курсу.
--    Поле исполняет LaunchGameUseCase.assertCurrencySupported (422
--    CURRENCY_NOT_SUPPORTED).
--
-- Значения можно менять и в админке (колонка «Возврат, %») — миграция задаёт
-- только стартовую точку и выполняется один раз.

UPDATE "games"
   SET "rtp" = 97,
       "rtp_demo" = 120,
       "supported_currencies" = '["RUB", "USDT_TRC20"]'::jsonb
 WHERE "external_game_id" = 'plinko';
